"""File-contract tests for the shipped CLI lab template (plan 005).

The CLI scaffold is generated by `labkit start --type cli`; these
tests pin what a fresh clone observably ships under
templates/new-cli-lab/, leaving prose to manual review (plan 005:
review learning intent, never assert incidental wording):

  * AC4: README.md and the reusable task1.sh exemplar ship - the
    exemplar is what generation renders every task<N>.sh from
  * AC4/AC6: every shipped shell file is comment guidance and
    blank workspace, so executing it runs nothing
  * AC5: no Terraform support files ship by default
  * AC1/AC8: the README marks the lab-owned details (title, link,
    requirements sections) instead of shipping fabricated ones
  * AC8/CLI-R1: the documented manual-setup block (the optional
    copy-by-hand path next to the generated workflow), executed the
    way a student pastes it, delivers the template files into a
    fresh lab and refuses to write into (or enter) a lab that
    already exists, spaces in the name included

Content tests read the real checkout the way a fresh clone would.
Setup tests copy the shipped template into disposable directories
and run only the block the README documents, with a stub gcloud
first on PATH so a doc bug that ever put cloud commands in the
block hits a logger instead of real credentials, and with bash's
inherited startup hooks (BASH_ENV, ENV, exported functions)
stripped so the child runs no ambient code.
"""

import os
import re
import shlex
import shutil
import subprocess
import tempfile
import unittest
from pathlib import Path
from unittest import mock

from util import GCLOUD_STUB, REPO_ROOT, noncomment_lines, snapshot_nofollow

CLI_TEMPLATE = REPO_ROOT / "templates" / "new-cli-lab"

# student work the documented setup must never overwrite or lose
STUDENT_README = "# My CLI lab\n\nMy own notes from working the lab.\n"
STUDENT_TASK = "#!/usr/bin/env bash\n# Task 1: my own work so far\necho mine\n"
STUDENT_EXTRA_TASK = "#!/usr/bin/env bash\n# Task 2: also mine, not a template file\n"


def make_setup_repo(parent: Path, existing: tuple[str, ...] = ()) -> Path:
    """A disposable checkout: the shipped template, a labs/
    collection, and per-slug student work in `existing`.

    Copies the real template files as the source a student copies
    from; every write stays inside parent.
    """
    repo = parent / "repo"
    template = repo / "templates" / "new-cli-lab"
    template.mkdir(parents=True)
    for name in ("README.md", "task1.sh"):
        shutil.copy2(CLI_TEMPLATE / name, template / name)
    labs = repo / "labs"
    labs.mkdir()
    for slug in existing:
        lab = labs / slug
        lab.mkdir()
        (lab / "README.md").write_text(STUDENT_README)
        (lab / "task1.sh").write_text(STUDENT_TASK)
        (lab / "task2.sh").write_text(STUDENT_EXTRA_TASK)
    return repo


def bash_env(parent: Path) -> dict:
    """The ambient environment plus a stub gcloud first on PATH.

    The setup block is directory work; the stub exists so a doc bug
    that ever put cloud commands in the block hits a logger, never
    real credentials. Bash's inherited hooks are stripped too: a
    non-interactive bash sources the file named by BASH_ENV at
    startup and imports exported functions (BASH_FUNC_*), and a
    POSIX-mode bash sources ENV, so any of those arriving from the
    calling environment would run code the test never wrote, free
    to touch files outside the fixture. Cloud-tool overrides are
    stripped the way stub_env strips them, and HOME lands in the
    fixture.
    """
    bin_dir = parent / "bin"
    home = parent / "home"
    bin_dir.mkdir(exist_ok=True)
    home.mkdir(exist_ok=True)
    gcloud = bin_dir / "gcloud"
    gcloud.write_text(GCLOUD_STUB)
    gcloud.chmod(0o755)
    env = {key: value for key, value in os.environ.items()
           if not key.startswith(("CLOUDSDK_", "GOOGLE_", "TF_",
                                  "BASH_FUNC_"))
           and key not in ("BASH_ENV", "ENV")}
    env["PATH"] = str(bin_dir) + os.pathsep + env.get("PATH", "")
    env["HOME"] = str(home)
    env["GCLOUD_LOG"] = str(parent / "gcloud.log")
    return env


def manual_setup_fence(readme_text: str) -> str:
    """The README's manual-copy block, located robustly.

    The generated workflow is the primary setup now, so the sh
    fences are located by what they do (copy the template files)
    rather than by position in the README.
    """
    for fence in re.findall(r"```sh\n(.*?)```", readme_text, re.DOTALL):
        if "cp templates/new-cli-lab/" in fence:
            return fence
    raise AssertionError("the shipped README documents no manual "
                        "setup block that copies the template files")


def run_documented_setup(repo: Path, slug: str, env: dict) -> tuple[int, Path]:
    """Execute the README's manual setup block the way a student
    pastes it.

    `<lab-slug>` is substituted exactly as the README instructs.
    Two probe lines appended after the block report the block's own
    exit status and the shell's final directory; the probes are
    harness, not documentation. Returns (status, final directory).
    """
    readme = (CLI_TEMPLATE / "README.md").read_text()
    script = manual_setup_fence(readme).replace("<lab-slug>", slug)
    result = subprocess.run(
        ["bash", "-c", script + '\necho "EXIT:$?"\npwd'],
        cwd=repo, env=env, input="", capture_output=True, text=True,
        timeout=30,
    )
    lines = result.stdout.splitlines()
    # the probes are the last EXIT: line and the line after it
    probe = max(i for i, line in enumerate(lines) if line.startswith("EXIT:"))
    status = int(lines[probe][len("EXIT:"):])
    cwd_after = Path(lines[probe + 1])
    return status, cwd_after


class CliTemplateContentTests(unittest.TestCase):
    def test_ac4_readme_and_task_exemplar_ship(self):
        # AC4: the CLI scaffold is README.md plus a task exemplar
        # students copy and renumber as task<N>.sh
        for name in ("README.md", "task1.sh"):
            path = CLI_TEMPLATE / name
            self.assertTrue(path.is_file(), f"{path} is not tracked yet")

    def test_ac4_shipped_shell_files_execute_nothing(self):
        # AC4/AC6: comments and student workspace only. A shipped
        # command would be a completed provisioning step, so every
        # shell file must run nothing as-is.
        for path in sorted(CLI_TEMPLATE.rglob("*.sh")):
            self.assertEqual(noncomment_lines(path), [],
                             f"pre-written commands shipped in {path}")

    def test_ac5_no_terraform_support_files_ship_by_default(self):
        # AC5: backend/providers/variables/tfvars belong to the
        # Terraform scaffold; a CLI lab adds files only when its
        # lab requires them.
        for path in sorted(CLI_TEMPLATE.rglob("*")):
            self.assertFalse(path.name.endswith((".tf", ".tfvars")),
                             f"{path} ships Terraform support by default")

    def test_ac1_ac8_readme_ships_markers_not_lab_details(self):
        # AC1/AC8: a manual copy fills the lab's own title, link,
        # and requirements sections; the template ships explicit
        # markers, never fabricated lab details.
        readme = (CLI_TEMPLATE / "README.md").read_text()
        for marker in ("__LAB_TITLE__", "__LAB_URL__", "__LAB_SECTIONS__"):
            self.assertIn(marker, readme)


class CliSetupBehaviorTests(unittest.TestCase):
    """CLI-R1/AC8: the setup a student copies must be safe to run.

    Each test builds a disposable checkout and executes the
    documented block against it. Behavior is what counts; the
    block's wording stays manual-review material.
    """

    def setUp(self):
        self._tmp = tempfile.TemporaryDirectory()
        self.addCleanup(self._tmp.cleanup)
        self.root = Path(self._tmp.name)

    def test_ac8_setup_delivers_template_files_into_a_fresh_lab(self):
        # CLI-R1/AC8: on a fresh name the documented setup works:
        # the lab directory appears, both template files land in it
        # byte for byte, and the student ends up inside it
        case = self.root / "fresh"
        repo = make_setup_repo(case)
        status, after = run_documented_setup(repo, "fresh-lab",
                                            bash_env(case))
        self.assertEqual(status, 0, "setup must succeed on a fresh name")
        lab = repo / "labs" / "fresh-lab"
        for name in ("README.md", "task1.sh"):
            self.assertEqual((lab / name).read_bytes(),
                             (CLI_TEMPLATE / name).read_bytes(), name)
        self.assertEqual(after.resolve(), lab.resolve(),
                         "setup should leave the student inside the new lab")
        self.assertEqual({p.name for p in (repo / "labs").iterdir()},
                         {"fresh-lab"},
                         "setup left entries under labs/ beside the lab")

    def test_ac8_setup_keeps_a_spaced_lab_name_one_path(self):
        # CLI-R1: quotes must keep a name with spaces one path:
        # exactly the named lab appears, both files land in it, and
        # the student ends up inside it
        case = self.root / "spaced"
        repo = make_setup_repo(case)
        status, after = run_documented_setup(repo, "fresh lab",
                                             bash_env(case))
        self.assertEqual(status, 0,
                         "setup must succeed with spaces in the name")
        lab = repo / "labs" / "fresh lab"
        for name in ("README.md", "task1.sh"):
            self.assertEqual((lab / name).read_bytes(),
                             (CLI_TEMPLATE / name).read_bytes(), name)
        self.assertEqual(after.resolve(), lab.resolve())
        self.assertEqual({p.name for p in (repo / "labs").iterdir()},
                         {"fresh lab"},
                         "an unquoted path split into several arguments")

    def test_ac8_setup_fails_closed_around_existing_labs(self):
        # CLI-R1/AC8: an existing lab is student work. The
        # documented setup must fail before copying, write nothing
        # anywhere under labs/, and leave the student outside the
        # lab it refused to touch, spaces in the name included.
        case = self.root / "existing"
        repo = make_setup_repo(case, existing=("existing-lab",
                                               "existing lab"))
        env = bash_env(case)
        for slug in ("existing-lab", "existing lab"):
            with self.subTest(slug=slug):
                before = snapshot_nofollow(repo / "labs")
                status, after = run_documented_setup(repo, slug, env)
                self.assertNotEqual(
                    status, 0, f"setup must refuse an existing {slug!r}")
                self.assertEqual(
                    snapshot_nofollow(repo / "labs"), before,
                    f"a refused setup still wrote into labs/ ({slug!r})")
                self.assertNotEqual(
                    after.resolve(), (repo / "labs" / slug).resolve(),
                    f"setup cd'd into the lab it refused ({slug!r})")

    def test_cli_r4_setup_child_runs_no_inherited_bash_hooks(self):
        # CLI-R4/AGENTS disposable-data safeguard: the subprocess
        # executing the documented setup must run no code the test
        # never wrote. A non-interactive bash sources the file
        # named by BASH_ENV at startup and imports exported
        # functions (BASH_FUNC_*) from the environment, so
        # inheriting either would let ambient shell hooks run
        # before the setup block and write outside the disposable
        # fixture. Neither may execute, and the setup must still
        # work through the real commands.
        case = self.root / "hooks"
        repo = make_setup_repo(case)
        ambient = case / "ambient"
        ambient.mkdir()
        startup_sentinel = ambient / "touched-by-startup-file"
        func_sentinel = ambient / "touched-by-imported-function"
        startup = ambient / "startup.sh"
        startup.write_text(
            "touch " + shlex.quote(str(startup_sentinel)) + "\n")
        cp_override = ("() { touch " + shlex.quote(str(func_sentinel))
                       + '; command cp "$@"; }')
        with mock.patch.dict(os.environ,
                             {"BASH_ENV": str(startup),
                              "BASH_FUNC_cp%%": cp_override}):
            env = bash_env(case)
        status, after = run_documented_setup(repo, "fresh-lab", env)
        # the documented setup still succeeds, through the real cp
        self.assertEqual(status, 0, "setup must still succeed")
        lab = repo / "labs" / "fresh-lab"
        self.assertEqual((lab / "README.md").read_bytes(),
                         (CLI_TEMPLATE / "README.md").read_bytes())
        self.assertFalse(startup_sentinel.exists(),
                         "the inherited BASH_ENV startup file executed")
        self.assertFalse(func_sentinel.exists(),
                         "an exported bash function was imported over cp")


if __name__ == "__main__":
    unittest.main()
