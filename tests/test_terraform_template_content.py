"""File-contract tests for the shipped Terraform lab template (plan 005).

The Terraform scaffold is generated by `labkit start --type
terraform`; these tests pin what a fresh clone observably ships
under templates/new-terraform-lab/, leaving prose to manual review
(plan 005: review learning intent, never assert incidental
wording):

  * AC3: README.md, the reusable task1.tf exemplar generation
    renders every task<N>.tf from, and the
    backend/providers/variables skeleton ship
  * AC3: no terraform.tfvars ships; generation creates it in the
    lab from the running lab's project/region/zone (and the
    optional manual path documents creating it locally), and the
    names the README documents are the names variables.tf declares
  * AC3/AC6: the task exemplar is comment guidance and blank
    workspace only, with no provider-specific resource types
  * AC1/AC8: the README marks the lab-owned details (title, link,
    requirements sections) instead of shipping fabricated ones
  * AC8: the documented manual-setup block (the optional
    copy-by-hand path next to the generated workflow), executed
    the way a student pastes it, delivers the template files into
    a fresh lab and refuses to write into (or enter) a lab that
    already exists, spaces in the name included
  * AC3: shipped .tf files pass `terraform fmt -check` when a
    terraform binary is available (the README tells students to
    run `terraform fmt`)

Prerequisites wording and the README's own-solution meaning are
learning intent: manual review, never wording-pinned here.

Content tests read the real checkout the way a fresh clone would.
Setup tests copy the shipped template into disposable directories
and run only the block the README documents, with a stub gcloud
first on PATH so a doc bug that ever put cloud commands in the
block hits a logger instead of real credentials, and with bash's
inherited startup hooks (BASH_ENV, ENV, exported functions)
stripped so the child runs no ambient code.
"""

import os
import re
import shlex
import shutil
import subprocess
import tempfile
import unittest
from pathlib import Path
from unittest import mock

from util import (GCLOUD_STUB, REPO_ROOT, noncomment_lines, snapshot_nofollow)

TF_TEMPLATE = REPO_ROOT / "templates" / "new-terraform-lab"

# AC3: what the Terraform scaffold ships. terraform.tfvars is
# deliberately absent: generation writes it into the lab from the
# running lab's values, so no concrete lab values ship tracked. The
# manual path documents creating the file locally instead.
SCAFFOLD_FILES = ("README.md", "task1.tf", "backend.tf", "providers.tf",
                  "variables.tf")

# student work the documented setup must never overwrite or lose
STUDENT_README = "# My Terraform lab\n\nMy own notes from working the lab.\n"
STUDENT_TASK = ('# Task 1\nresource "google_compute_network" "net" {\n'
                '  name = "vpc"\n}\n')
STUDENT_EXTRA_TASK = "# Task 2: also mine, not a template file\n"
STUDENT_TFVARS = 'project_id = "qwiklabs-gcp-00-mine"\n'
STUDENT_STATE = '{"project": "qwiklabs-gcp-00-mine"}'


def make_setup_repo(parent: Path, existing: tuple[str, ...] = ()) -> Path:
    """A disposable checkout: the shipped template, a labs/
    collection, and per-slug student work in `existing`.

    Copies the real template files as the source a student copies
    from; every write stays inside parent. Existing labs carry
    Terraform student work - a started task, local tfvars and
    state - because those are exactly what a refused setup must
    leave alone.
    """
    repo = parent / "repo"
    template = repo / "templates" / "new-terraform-lab"
    template.mkdir(parents=True)
    for name in SCAFFOLD_FILES:
        shutil.copy2(TF_TEMPLATE / name, template / name)
    labs = repo / "labs"
    labs.mkdir()
    for slug in existing:
        lab = labs / slug
        lab.mkdir()
        (lab / "README.md").write_text(STUDENT_README)
        (lab / "task1.tf").write_text(STUDENT_TASK)
        (lab / "task2.tf").write_text(STUDENT_EXTRA_TASK)
        (lab / "terraform.tfvars").write_text(STUDENT_TFVARS)
        (lab / "terraform.tfstate").write_text(STUDENT_STATE)
    return repo


def bash_env(parent: Path) -> dict:
    """The ambient environment plus a stub gcloud first on PATH.

    The setup block is directory work; the stub exists so a doc bug
    that ever put cloud commands in the block hits a logger, never
    real credentials. Bash's inherited hooks are stripped too: a
    non-interactive bash sources the file named by BASH_ENV at
    startup and imports exported functions (BASH_FUNC_*), and a
    POSIX-mode bash sources ENV, so any of those arriving from the
    calling environment would run code the test never wrote, free
    to touch files outside the fixture. Cloud-tool and Terraform
    env overrides are stripped the way stub_env strips them, and
    HOME lands in the fixture.
    """
    bin_dir = parent / "bin"
    home = parent / "home"
    bin_dir.mkdir(exist_ok=True)
    home.mkdir(exist_ok=True)
    gcloud = bin_dir / "gcloud"
    gcloud.write_text(GCLOUD_STUB)
    gcloud.chmod(0o755)
    env = {key: value for key, value in os.environ.items()
           if not key.startswith(("CLOUDSDK_", "GOOGLE_", "TF_",
                                  "BASH_FUNC_"))
           and key not in ("BASH_ENV", "ENV")}
    env["PATH"] = str(bin_dir) + os.pathsep + env.get("PATH", "")
    env["HOME"] = str(home)
    env["GCLOUD_LOG"] = str(parent / "gcloud.log")
    return env


def manual_setup_fence(readme_text: str) -> str:
    """The README's manual-copy block, located robustly.

    The generated workflow is the primary setup now, so the sh
    fences are located by what they do (copy the template files)
    rather than by position in the README.
    """
    for fence in re.findall(r"```sh\n(.*?)```", readme_text, re.DOTALL):
        if "cp templates/new-terraform-lab/" in fence:
            return fence
    raise AssertionError("the shipped README documents no manual "
                        "setup block that copies the template files")


def run_documented_setup(repo: Path, slug: str, env: dict) -> tuple[int, Path]:
    """Execute the README's manual setup block the way a student
    pastes it.

    `<lab-slug>` is substituted exactly as the README instructs.
    Two probe lines appended after the block report the block's own
    exit status and the shell's final directory; the probes are
    harness, not documentation. Returns (status, final directory).
    """
    readme = (TF_TEMPLATE / "README.md").read_text()
    script = manual_setup_fence(readme).replace("<lab-slug>", slug)
    result = subprocess.run(
        ["bash", "-c", script + '\necho "EXIT:$?"\npwd'],
        cwd=repo, env=env, input="", capture_output=True, text=True,
        timeout=30,
    )
    lines = result.stdout.splitlines()
    # the probes are the last EXIT: line and the line after it
    probe = max(i for i, line in enumerate(lines) if line.startswith("EXIT:"))
    status = int(lines[probe][len("EXIT:"):])
    cwd_after = Path(lines[probe + 1])
    return status, cwd_after


class TerraformTemplateContentTests(unittest.TestCase):
    def test_ac3_scaffold_files_ship(self):
        # AC3: the Terraform scaffold is its README, a reusable
        # task exemplar, and the backend/providers/variables
        # skeleton (AC5: those support files belong to this type)
        for name in SCAFFOLD_FILES:
            path = TF_TEMPLATE / name
            self.assertTrue(path.is_file(), f"{path} is not tracked yet")

    def test_ac3_no_tfvars_file_ships(self):
        # AC3: terraform.tfvars is generated into the lab from the
        # running lab's values (or created by hand on the manual
        # path), so no tfvars file may ship with the template - a
        # shipped one would carry lab values into the repository.
        # Harmless extra files (a NOTES.md, say) stay allowed; this
        # guards the meaningful boundary only.
        shipped = list(TF_TEMPLATE.rglob("*.tfvars*"))
        self.assertEqual(shipped, [],
                         "tfvars files ship with the template")

    def test_ac3_ac6_task_exemplar_is_comment_guidance_only(self):
        # AC3/AC6: comments and student workspace only. A shipped
        # resource or data block would be a completed solution
        # step, and a shipped provider-specific resource type
        # would be a title-inferred specific; specifics are added
        # manually when preparing a particular lab.
        exemplar = (TF_TEMPLATE / "task1.tf").read_text()
        self.assertEqual(noncomment_lines(TF_TEMPLATE / "task1.tf"), [],
                         "declarative configuration shipped in task1.tf")
        self.assertNotIn("google_", exemplar,
                         "provider-specific resource types shipped")

    def test_ac3_support_files_match_the_readme_tfvars_example(self):
        # AC3/AC8: the README has the student create terraform.tfvars
        # by hand; the names it documents must be exactly the names
        # variables.tf declares (a mismatched tfvars name is
        # silently ignored by Terraform), and the skeleton must
        # carry the local backend whose state reset deletes and the
        # google provider the lab authenticates with
        readme = (TF_TEMPLATE / "README.md").read_text()
        fence = re.search(r"```hcl\n(.*?)```", readme, re.DOTALL)
        self.assertIsNotNone(
            fence, "the README must document creating terraform.tfvars")
        documented = set(re.findall(r"^(\w+)\s*=", fence.group(1),
                                    re.MULTILINE))
        self.assertTrue(documented, "the tfvars example assigns nothing")
        declared = set(re.findall(r'^\s*variable\s+"(\w+)"',
                                  (TF_TEMPLATE / "variables.tf").read_text(),
                                  re.MULTILINE))
        self.assertEqual(documented, declared,
                         "the README's tfvars names and variables.tf disagree")
        self.assertIn('backend "local"',
                      (TF_TEMPLATE / "backend.tf").read_text())
        self.assertIn('provider "google"',
                      (TF_TEMPLATE / "providers.tf").read_text())

    def test_ac1_ac8_readme_ships_markers_not_lab_details(self):
        # AC1/AC8: a manual copy fills the lab's own title, link,
        # and requirements sections; the template ships explicit
        # markers, never fabricated lab details
        readme = (TF_TEMPLATE / "README.md").read_text()
        for marker in ("__LAB_TITLE__", "__LAB_URL__", "__LAB_SECTIONS__"):
            self.assertIn(marker, readme)


class TerraformSetupBehaviorTests(unittest.TestCase):
    """AC8/AGENTS disposable-data safeguard: the setup a student
    copies must be safe to run.

    Each test builds a disposable checkout and executes the
    documented block against it. Behavior is what counts; the
    block's wording stays manual-review material.
    """

    def setUp(self):
        self._tmp = tempfile.TemporaryDirectory()
        self.addCleanup(self._tmp.cleanup)
        self.root = Path(self._tmp.name)

    def test_ac8_setup_delivers_template_files_into_a_fresh_lab(self):
        # AC8: on a fresh name the documented setup works: the lab
        # directory appears, every template file lands in it byte
        # for byte, and the student ends up inside it
        case = self.root / "fresh"
        repo = make_setup_repo(case)
        status, after = run_documented_setup(repo, "fresh-lab",
                                             bash_env(case))
        self.assertEqual(status, 0, "setup must succeed on a fresh name")
        lab = repo / "labs" / "fresh-lab"
        for name in SCAFFOLD_FILES:
            self.assertEqual((lab / name).read_bytes(),
                             (TF_TEMPLATE / name).read_bytes(), name)
        self.assertEqual(after.resolve(), lab.resolve(),
                         "setup should leave the student inside the new lab")
        self.assertEqual({p.name for p in (repo / "labs").iterdir()},
                         {"fresh-lab"},
                         "setup left entries under labs/ beside the lab")

    def test_ac8_setup_keeps_a_spaced_lab_name_one_path(self):
        # AC8: quotes must keep a name with spaces one path:
        # exactly the named lab appears, every file lands in it,
        # and the student ends up inside it
        case = self.root / "spaced"
        repo = make_setup_repo(case)
        status, after = run_documented_setup(repo, "fresh lab",
                                             bash_env(case))
        self.assertEqual(status, 0,
                         "setup must succeed with spaces in the name")
        lab = repo / "labs" / "fresh lab"
        for name in SCAFFOLD_FILES:
            self.assertEqual((lab / name).read_bytes(),
                             (TF_TEMPLATE / name).read_bytes(), name)
        self.assertEqual(after.resolve(), lab.resolve())
        self.assertEqual({p.name for p in (repo / "labs").iterdir()},
                         {"fresh lab"},
                         "an unquoted path split into several arguments")

    def test_ac8_setup_fails_closed_around_existing_labs(self):
        # AC8: an existing lab is student work, state and tfvars
        # included. The documented setup must fail before copying,
        # write nothing anywhere under labs/, and leave the
        # student outside the lab it refused to touch, spaces in
        # the name included.
        case = self.root / "existing"
        repo = make_setup_repo(case, existing=("existing-lab",
                                                "existing lab"))
        env = bash_env(case)
        for slug in ("existing-lab", "existing lab"):
            with self.subTest(slug=slug):
                before = snapshot_nofollow(repo / "labs")
                status, after = run_documented_setup(repo, slug, env)
                self.assertNotEqual(
                    status, 0, f"setup must refuse an existing {slug!r}")
                self.assertEqual(
                    snapshot_nofollow(repo / "labs"), before,
                    f"a refused setup still wrote into labs/ ({slug!r})")
                self.assertNotEqual(
                    after.resolve(), (repo / "labs" / slug).resolve(),
                    f"setup cd'd into the lab it refused ({slug!r})")

    def test_ac8_setup_child_runs_no_inherited_bash_hooks(self):
        # AGENTS disposable-data safeguard: the subprocess
        # executing the documented setup must run no code the test
        # never wrote. A non-interactive bash sources the file
        # named by BASH_ENV at startup and imports exported
        # functions (BASH_FUNC_*) from the environment, so
        # inheriting either would let ambient shell hooks run
        # before the setup block and write outside the disposable
        # fixture. Neither may execute, and the setup must still
        # work through the real commands.
        case = self.root / "hooks"
        repo = make_setup_repo(case)
        ambient = case / "ambient"
        ambient.mkdir()
        startup_sentinel = ambient / "touched-by-startup-file"
        func_sentinel = ambient / "touched-by-imported-function"
        startup = ambient / "startup.sh"
        startup.write_text(
            "touch " + shlex.quote(str(startup_sentinel)) + "\n")
        cp_override = ("() { touch " + shlex.quote(str(func_sentinel))
                       + '; command cp "$@"; }')
        with mock.patch.dict(os.environ,
                             {"BASH_ENV": str(startup),
                              "BASH_FUNC_cp%%": cp_override}):
            env = bash_env(case)
        status, after = run_documented_setup(repo, "fresh-lab", env)
        # the documented setup still succeeds, through the real cp
        self.assertEqual(status, 0, "setup must still succeed")
        lab = repo / "labs" / "fresh-lab"
        self.assertEqual((lab / "README.md").read_bytes(),
                         (TF_TEMPLATE / "README.md").read_bytes())
        self.assertFalse(startup_sentinel.exists(),
                         "the inherited BASH_ENV startup file executed")
        self.assertFalse(func_sentinel.exists(),
                         "an exported bash function was imported over cp")


class TerraformFormatTests(unittest.TestCase):
    def test_ac3_shipped_tf_files_pass_terraform_fmt_check(self):
        # AC3: the README tells students to run `terraform fmt`; a
        # template that arrives needing rewrites undercuts that.
        # Read-only check mode: never init, apply, or auth.
        if shutil.which("terraform") is None:
            self.skipTest("terraform not installed")
        result = subprocess.run(
            ["terraform", "fmt", "-check", str(TF_TEMPLATE)],
            capture_output=True, text=True, timeout=60,
        )
        self.assertEqual(
            result.returncode, 0,
            "shipped .tf files are not canonically formatted:\n"
            + result.stdout + result.stderr)


if __name__ == "__main__":
    unittest.main()
